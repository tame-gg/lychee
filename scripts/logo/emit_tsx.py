"""Emit the tame.gg React component for the Lychee mark from the same 48-cell grid.
Run: python3 emit_tsx.py <tame.gg>/app/(portal)/_components/lychee-mark.tsx"""
import sys
from gen import proc, PAL
rows = proc(48)
paths = {}  # colour -> horizontal runs merged into one path
for y, r in enumerate(rows):
    x = 0
    while x < len(r):
        c = r[x]; e = x
        while e < len(r) and r[e] == c: e += 1
        if c != '.': paths.setdefault(PAL[c], []).append(f'M{x} {y}h{e-x}v1h-{e-x}z')
        x = e
entries = '\n'.join(f"  ['{fill}', '{''.join(d)}']," for fill, d in paths.items())
out = f"""/* =====================================================================
   The Lychee mark: a red-pink pixel lychee (bumpy shell with gold
   highlights, a stem and a leaf), drawn on a 48-cell grid. Generated by
   tame-gg/lychee scripts/logo (emit_tsx.py) so the site card and the app
   icon are the same pixels; do not edit by hand.
   ===================================================================== */

/* [colour, path]: one path per colour, each pixel run as a 1-cell-high rectangle */
const PATHS: ReadonlyArray<readonly [string, string]> = [
{entries}
];

export function LycheeMark({{ size = 96, className }}: {{ size?: number; className?: string }}) {{
  return (
    <svg
      className={{className}}
      width={{size}}
      height={{size}}
      viewBox="0 0 48 48"
      shapeRendering="crispEdges"
      aria-hidden="true"
    >
      {{PATHS.map(([fill, d]) => (
        <path key={{fill}} fill={{fill}} d={{d}} />
      ))}}
    </svg>
  );
}}
"""
open(sys.argv[1], 'w').write(out)
