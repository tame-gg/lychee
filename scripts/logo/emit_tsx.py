"""Emit the tame.gg React component for the Lychee mark from the same 48-cell grid."""
import sys
from gen import proc, PAL
rows = proc(48)
rects = []
for y, r in enumerate(rows):
    x = 0
    while x < len(r):
        c = r[x]; e = x
        while e < len(r) and r[e] == c: e += 1
        if c != '.': rects.append(f"  [{x}, {y}, {e-x}, '{PAL[c]}'],")
        x = e
out = f"""/* =====================================================================
   The Lychee mark: a gold pixel lychee (bumpy skin, leaf, one peeled patch
   showing the white flesh), drawn on a 48-cell grid in the same gold tones
   as the IsoBlock faces in gold-block.tsx. Generated by
   tame-gg/lychee scripts/logo (emit_tsx.py) so the site card and the app
   icon are the same pixels; do not edit by hand.
   ===================================================================== */

/* [x, y, run length, colour] */
const RUNS: ReadonlyArray<readonly [number, number, number, string]> = [
{chr(10).join(rects)}
];

export function LycheeMark({{ size = 96, className }}: {{ size?: number; className?: string }}) {{
  return (
    <svg
      className={{className}}
      width={{size}}
      height={{size}}
      viewBox="0 0 48 48"
      shapeRendering="crispEdges"
      aria-hidden="true"
    >
      {{RUNS.map(([x, y, w, fill]) => (
        <rect key={{`${{x}}-${{y}}`}} x={{x}} y={{y}} width={{w + 0.02}} height={{1.02}} fill={{fill}} />
      ))}}
    </svg>
  );
}}
"""
open(sys.argv[1], 'w').write(out)
